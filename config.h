#pragma once

// ------------------------- Wi-Fi --------------------------------------------
#define WIFI_SSID         "RTm"
#define WIFI_PASS         "q12345678"
#define WIFI_HOSTNAME     "esp32-swd"        // имя в сети (mDNS: esp32-swd.local)

// ------------------------- Пины ESP32  ->  STM32 (SWD) ----------------------
//   ESP32 GPIO18  -> STM32 SWCLK (PA14, на гребёнке "CLK")
//   ESP32 GPIO23  -> STM32 SWDIO (PA13, на гребёнке "DIO")
//   ESP32 GND     -> STM32 GND
//   ESP32 3V3     -> STM32 3V3   (только если STM32 не питается от USB!)
#define PIN_SWCLK         18
#define PIN_SWDIO         23

// Опциональный NRST (не обязателен, гребёнка у вас из 4 пинов).
// Если раскомментировать и подключить к пину RESET платы STM32, появится
// режим "connect under reset" для целей, где прошивка отключила SWD.
//#define PIN_NRST          5

// ------------------------- Скорость SWD ------------------------------------
// Значение = задержка полутакта в итерациях NOP (меньше = быстрее).
//   8   ~ 2   МГц   (быстро, может не работать на плохих проводах)
//   24  ~ 1   МГц   (по умолчанию)
//   60  ~ 400 кГц
//   150 ~ 150 кГц   (медленно, максимально надёжно)
#define SWD_SPEED_DEFAULT 24

// ------------------------- Прошивка -----------------------------------------
#define FLASH_LOAD_ADDR     0x08000000UL     // начало флеша STM32F103
#define MAX_FIRMWARE_SIZE   (128UL * 1024UL) // защита от слишком больших файлов
#define FIRMWARE_PATH       "/firmware.bin"  // файл в LittleFS (SPIFFS-раздел)

// ------------------------- Прочее -------------------------------------------
#define SWD_WAIT_TIMEOUT_MS 5000    // сколько ждать ответ WAIT от цели
#define APP_LOG_SIZE        4096    // сколько байт лога держать в памяти
#define ENABLE_MDNS         1       // 1 = поднять mDNS (esp32-swd.local)
#define STATUS_PERIOD_MS    700     // период опроса статуса веб-страницей
